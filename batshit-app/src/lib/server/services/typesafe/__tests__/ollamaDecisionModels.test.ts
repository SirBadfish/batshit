describe('listOllamaDecisionModels', () => {
  it('keeps only models whose capabilities include decision, with the num_ctx Ollama gives each', async () => {
    const { calls, fetchImpl } = fakeOllama()
    const list = await listOllamaDecisionModels('http://127.0.0.1:11434', { fetch: fetchImpl })
    expect(list).toEqual({ ok: true, models: [{ name: 'clef-flash:latest', contextTokens: 16384 }], otherModelCount: 3 })
    // One list read, then /api/show only for the decision model (no show for chat or embedding models).
    expect(calls.map((call) => call.url)).toEqual(['http://127.0.0.1:11434/api/tags', 'http://127.0.0.1:11434/api/show'])
    expect(JSON.parse(String(calls[1].init.body))).toEqual({ model: 'clef-flash:latest' })
    // Round 1, S1: no read ever follows a redirect.
    expect(calls.map((call) => call.init.redirect)).toEqual(['error', 'error'])
  })

  it('asks /api/show about a model an older Ollama lists without capabilities', async () => {
    const tags = { models: [{ name: 'nimble:latest' }, { name: 'llama3:8b' }] }
    const { calls, fetchImpl } = fakeOllama({
      tags,
      shows: {
        'nimble:latest': { capabilities: ['decision'], parameters: 'stop "<|im_end|>"\nnum_ctx 8192' },
        'llama3:8b': { capabilities: ['completion'] }
      }
    })
    const list = await listOllamaDecisionModels('http://192.168.1.20:11434', { fetch: fetchImpl })
    expect(list).toEqual({ ok: true, models: [{ name: 'nimble:latest', contextTokens: 8192 }], otherModelCount: 1 })
    expect(calls.filter((call) => call.url.endsWith('/api/show'))).toHaveLength(2)
  })

  it('answers with a sentence when Ollama cannot be read or does not answer like Ollama', async () => {
    const down = await listOllamaDecisionModels('http://127.0.0.1:11434', {
      fetch: async () => {
        throw new TypeError('fetch failed')
      }
    })
    expect(down).toMatchObject({ ok: false })
    if (!down.ok) expect(down.error).toMatch(/could not read Ollama's model list at http:\/\/127\.0\.0\.1:11434/)
    const notOllama = await listOllamaDecisionModels('http://127.0.0.1:8080', { fetch: fakeOllama({ tags: { data: [] } }).fetchImpl })
    expect(notOllama).toEqual({ ok: false, error: 'http://127.0.0.1:8080 did not answer like Ollama (no model list).' })
    const refused = await listOllamaDecisionModels('http://127.0.0.1:11434', { fetch: fakeOllama({ tagsStatus: 500 }).fetchImpl })
    expect(refused).toMatchObject({ ok: false })
  })
})

describe('readOllamaNumCtx / readOllamaContextTokens', () => {
  it('reads num_ctx from the parameters text, and nothing else', () => {
    expect(readOllamaNumCtx(CAPTURED_SHOW_CLEF_FLASH)).toBe(16384)
    expect(readOllamaNumCtx({ parameters: 'temperature 0.7\nnum_ctx 65536\nstop "x"' })).toBe(65536)
    expect(readOllamaNumCtx({ parameters: 'temperature 0.7' })).toBeNull()
    expect(readOllamaNumCtx({ parameters: 'num_ctx_extra 4' })).toBeNull()
    expect(readOllamaNumCtx({ model_info: { 'clef.context_length': 262144 } })).toBeNull()
    expect(readOllamaNumCtx(null)).toBeNull()
  })

  it('caches the answer a minute per server and model, and reads null (never a throw) when Ollama cannot say', async () => {
    const { calls, fetchImpl } = fakeOllama()
    let clock = 1_000
    const now = () => clock
    const read = { status: 'read', contextTokens: 16384 }
    expect(await readOllamaContextTokens('http://127.0.0.1:11434', 'clef-flash:latest', { fetch: fetchImpl, now })).toEqual(read)
    clock += 59_000
    expect(await readOllamaContextTokens('http://127.0.0.1:11434', 'clef-flash:latest', { fetch: fetchImpl, now })).toEqual(read)
    expect(calls).toHaveLength(1)
    clock += 2_000
    await readOllamaContextTokens('http://127.0.0.1:11434', 'clef-flash:latest', { fetch: fetchImpl, now })
    expect(calls).toHaveLength(2)

    const failing = vi.fn<TypesafeFetch>(async () => {
      throw new TypeError('fetch failed')
    })
    expect(await readOllamaContextTokens('http://10.0.0.9:11434', 'clef-flash', { fetch: failing })).toEqual({ status: 'read', contextTokens: null })
  })
})

describe('readOllamaContextTokens answers to the caller (review round 1, M1)', () => {
  /** An Ollama that answers `/api/show` only after `delayMs` (a sleeping LAN computer waking up), or never. */
  function slowShow(delayMs: number | null) {
    const calls: string[] = []
    const fetchImpl: TypesafeFetch = (url, init) =>
      new Promise((resolve, reject) => {
        calls.push(url)
        const signal = init.signal as AbortSignal | undefined
        if (delayMs !== null) setTimeout(() => resolve(json(200, CAPTURED_SHOW_CLEF_FLASH)), delayMs)
        signal?.addEventListener('abort', () => reject(new DOMException('aborted', 'AbortError')), { once: true })
      })
    return { calls, fetchImpl }
  }

  it("stops waiting at the caller's deadline; the shared read goes on and fills the cache for the next call", async () => {
    const { calls, fetchImpl } = slowShow(300)
    // The outcome is the discriminator (without the caller's deadline it would wait and read): no wall-clock window.
    const first = await readOllamaContextTokens('http://192.168.1.20:11434', 'clef-flash:latest', { fetch: fetchImpl, deadlineMs: 50 })
    expect(first).toEqual({ status: 'deadline' })
    // The shared read finishes in the background; the next call reads the cache without a new request.
    await new Promise((resolve) => setTimeout(resolve, 350))
    expect(await readOllamaContextTokens('http://192.168.1.20:11434', 'clef-flash:latest', { fetch: fetchImpl, deadlineMs: 50 })).toEqual({
      status: 'read',
      contextTokens: 16384
    })
    expect(calls).toHaveLength(1)
  })

  it('ends at once when the caller is stopped, and a call already past its deadline or stopped reads nothing', async () => {
    const { calls, fetchImpl } = slowShow(null)
    const controller = new AbortController()
    const pending = readOllamaContextTokens('http://192.168.1.20:11434', 'nimble', { fetch: fetchImpl, signal: controller.signal })
    setTimeout(() => controller.abort(), 20)
    // Without the caller's signal it would end only at the read's own 4,000 ms ceiling, as a read.
    expect(await pending).toEqual({ status: 'aborted' })

    __resetOllamaContextCacheForTests()
    const stopped = new AbortController()
    stopped.abort()
    expect(await readOllamaContextTokens('http://10.0.0.5:11434', 'nimble', { fetch: fetchImpl, signal: stopped.signal })).toEqual({ status: 'aborted' })
    expect(await readOllamaContextTokens('http://10.0.0.5:11434', 'nimble', { fetch: fetchImpl, deadlineMs: 0 })).toEqual({ status: 'deadline' })
    expect(calls).toHaveLength(1)
  })

  it('shares one read per server and model between lanes that ask at the same time', async () => {
    const { calls, fetchImpl } = slowShow(40)
    const [a, b, c] = await Promise.all([
      readOllamaContextTokens('http://192.168.1.20:11434', 'clef-flash:latest', { fetch: fetchImpl, deadlineMs: 2_000 }),
      readOllamaContextTokens('http://192.168.1.20:11434', 'clef-flash:latest', { fetch: fetchImpl, deadlineMs: 2_000 }),
      readOllamaContextTokens('http://192.168.1.20:11434', 'clef-flash:latest', { fetch: fetchImpl })
    ])
    expect([a, b, c]).toEqual([
      { status: 'read', contextTokens: 16384 },
      { status: 'read', contextTokens: 16384 },
      { status: 'read', contextTokens: 16384 }
    ])
    expect(calls).toHaveLength(1)
  })
})
